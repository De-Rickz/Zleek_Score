"""
One-time cleanup for markets.status, which was stored as 'open' for every row
before gamma_client mapped Gamma's closed/archived fields.

Reads only: market ids from the DB (any role with SELECT on markets), and each
market's current state from the Gamma API. Writes a SQL file; it never writes to
the database. Apply the SQL yourself with a role that can UPDATE markets.

    DATABASE_URL=... .venv/bin/python scripts/gen_status_cleanup.py out.sql
"""
import asyncio
import os
import sys

import asyncpg
import httpx

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "ingestion"))
from gamma_client import BASE_URL, parse_markets  # same status mapping as the worker

BATCH = 100        # Gamma caps limit at 100
GAP_SEC = 0.4      # stay under Gamma's rate limit


async def fetch_closed(client, ids):
    # Gamma filters by id but hides closed markets unless closed=true, so this
    # returns exactly the requested markets that are closed.
    params = [("id", i) for i in ids] + [("closed", "true"), ("limit", BATCH)]
    for attempt in range(4):
        resp = await client.get("/markets", params=params)
        if resp.status_code != 429:
            resp.raise_for_status()
            return resp.json()
        await asyncio.sleep(5 * (attempt + 1))
    resp.raise_for_status()


async def main(out_path):
    conn = await asyncpg.connect(os.environ["DATABASE_URL"],
                                 server_settings={"default_transaction_read_only": "on"})
    ids = [r["id"] for r in await conn.fetch("SELECT id FROM markets WHERE status = 'open' ORDER BY id")]
    await conn.close()

    changes = {}
    async with httpx.AsyncClient(base_url=BASE_URL, timeout=30.0) as client:
        for n in range(0, len(ids), BATCH):
            for m in parse_markets(await fetch_closed(client, ids[n:n + BATCH])):
                if m["status"] != "open":
                    changes[m["id"]] = m["status"]
            if n // BATCH % 50 == 0:
                print(f"{n + BATCH}/{len(ids)} checked, {len(changes)} to change", file=sys.stderr)
            await asyncio.sleep(GAP_SEC)

    with open(out_path, "w") as f:
        f.write(f"-- Generated by scripts/gen_status_cleanup.py: {len(changes)} of {len(ids)} 'open' markets are closed on Gamma.\n")
        f.write("-- Only touches rows still 'open', so it never overwrites a newer status from the worker.\n")
        f.write("BEGIN;\nUPDATE markets m SET status = v.status\nFROM (VALUES\n")
        f.write(",\n".join(f"  ('{i}', '{s}')" for i, s in sorted(changes.items())))
        f.write("\n) AS v(id, status)\nWHERE m.id = v.id AND m.status = 'open';\nCOMMIT;\n")
    print(f"wrote {out_path}: {len(changes)} updates", file=sys.stderr)


if __name__ == "__main__":
    asyncio.run(main(sys.argv[1]))
